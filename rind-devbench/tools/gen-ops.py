#!/usr/bin/env python3
"""Writes src/ops.rs from admin/bench-report's SECTIONS, LIBRARIES, REQUIRED and
CRATES, so the app's list of operations is the report's, never a copy by hand.
Usage: tools/gen-ops.py [--check]"""
import importlib.machinery, importlib.util, json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
loader = importlib.machinery.SourceFileLoader("bench_report", os.path.join(root, "admin", "bench-report"))
spec = importlib.util.spec_from_loader("bench_report", loader)
br = importlib.util.module_from_spec(spec)
loader.exec_module(br)
def s(x):
    return json.dumps(x)
out = ["// @generated by tools/gen-ops.py from admin/bench-report. Do not edit.", "",
       "/// (section, operation template with `{lib}`), in report order.",
       "pub const OPERATIONS: &[(&str, &str)] = &["]
for section, ops in br.SECTIONS:
    for op in ops:
        out.append(f"    ({s(section)}, {s(op)}),")
out += ["];", "", "/// rind-bench row name -> report library name.", "pub const LIBRARIES: &[(&str, &str)] = &["]
for row, name in br.LIBRARIES.items():
    out.append(f"    ({s(row)}, {s(name)}),")
out += ["];", "", "/// Library -> (arch, CPU features it needs, as rind-cpuid names them).",
        "pub const REQUIRED: &[(&str, &str, &[&str])] = &["]
for lib, arches in br.REQUIRED.items():
    for arch, feats in arches.items():
        out.append(f"    ({s(lib)}, {s(arch)}, &[{', '.join(s(f) for f in feats)}]),")
out += ["];", "", "/// Library -> crates whose versions a result records.", "pub const CRATES: &[(&str, &[&str])] = &["]
for lib, crates in br.CRATES.items():
    out.append(f"    ({s(lib)}, &[{', '.join(s(c) for c in crates)}]),")
out += ["];", ""]
text = "\n".join(out)
path = os.path.join(os.path.dirname(here), "src", "ops.rs")
if "--check" in sys.argv:
    sys.exit(0 if open(path).read() == text else "src/ops.rs is out of date: run tools/gen-ops.py")
open(path, "w").write(text)
print(f"wrote {path}: {sum(len(o) for _, o in br.SECTIONS)} operations")
