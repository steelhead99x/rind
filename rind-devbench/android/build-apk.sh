#!/bin/bash
# Builds RindBench-android.apk without Gradle: cargo (NDK clang) -> javac -> d8 -> aapt2 -> zipalign -> apksigner.
# Needs ANDROID_HOME (SDK with build-tools 35, platforms/android-35, ndk), JDK 17+, rustup target aarch64-linux-android.
set -eu
# CPU denies set environment variables, which is only safe before a process starts a second thread.
# An Android app's process is multi-threaded before any of our code runs, so there is no such point.
if [ -n "${RIND_DEVBENCH_DENY:-}" ]; then
  echo "RIND_DEVBENCH_DENY is not supported on Android (no thread-free point to set the environment); unset it" >&2
  exit 1
fi
cd "$(dirname "$0")"
HERE=$PWD
SDK=${ANDROID_HOME:-$HOME/Android/Sdk}
BT=$SDK/build-tools/35.0.0
JAR=$SDK/platforms/android-35/android.jar
NDK=${ANDROID_NDK_HOME:-$(ls -d $SDK/ndk/* | sort -V | tail -1)}
TC=$NDK/toolchains/llvm/prebuilt/linux-x86_64/bin
API=30
export CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER=$TC/aarch64-linux-android$API-clang
export CC_aarch64_linux_android=$TC/aarch64-linux-android$API-clang
export CXX_aarch64_linux_android=$TC/aarch64-linux-android$API-clang++
export AR_aarch64_linux_android=$TC/llvm-ar
export ANDROID_NDK_HOME=$NDK ANDROID_NDK_ROOT=$NDK
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$HOME/rind-devbench/target}
export PATH=$TC:$PATH
OUT=$HERE/out; rm -rf $OUT; mkdir -p $OUT/classes $OUT/apk/lib/arm64-v8a $OUT/apk/assets $OUT/flat $OUT/gen
(cd .. && nice -n 19 cargo +1.98.1 build --release --lib --target aarch64-linux-android -j ${JOBS:-6} ${CARGO_FEATURES---features __bench_openssl})
cp $CARGO_TARGET_DIR/aarch64-linux-android/release/librind_devbench.so $OUT/apk/lib/arm64-v8a/
$TC/llvm-strip --strip-debug $OUT/apk/lib/arm64-v8a/librind_devbench.so
cp -R ../../rind-rustls/tests/keys $OUT/apk/assets/keys
# The collector the app fills in by itself (no typing): USB via `adb reverse` on
# 127.0.0.1:PORT first, then a LAN address if one is given. Set with
# COLLECTOR_HOST / COLLECTOR_PORT. 9103 = Android (iPads use 9101/9102).
COLLECTOR_HOST=${COLLECTOR_HOST:-} COLLECTOR_PORT=${COLLECTOR_PORT:-9103}
# DEVICE_RUNNER=1 makes a build for an unattended device runner: only it honours
# the host, port and autostart extras, since any app can start the launcher.
case ${DEVICE_RUNNER:-0} in 1) RUNNER=true ;; *) RUNNER=false ;; esac
mkdir -p $OUT/gen/io/github/steelhead99x/rindbench
cat > $OUT/gen/io/github/steelhead99x/rindbench/Collector.java <<J
package io.github.steelhead99x.rindbench;
/** Generated by build-apk.sh. */
final class Collector { static final String HOST = "$COLLECTOR_HOST"; static final int PORT = $COLLECTOR_PORT; static final boolean RUNNER = $RUNNER; }
J
# Compile every resource under res/ (icons, themes, and any notice, font or raw file added later),
# so nothing added there is silently left out of the app.
rm -rf $OUT/flat; mkdir -p $OUT/flat
$BT/aapt2 compile --dir res -o $OUT/flat/res.zip
$BT/aapt2 link -o $OUT/base.apk -I $JAR --manifest AndroidManifest.xml -A $OUT/apk/assets \
  --min-sdk-version 26 --target-sdk-version 35 --auto-add-overlay $OUT/flat/res.zip

JH=${JAVA_HOME:-}; JAVAC=${JH:+$JH/bin/}javac
ZXING=$HERE/libs/zxing-core-3.5.3.jar
CP=$JAR
[ -f "$ZXING" ] && CP=$JAR:$ZXING
$JAVAC --release 11 -cp $CP -d $OUT/classes $(find src $OUT/gen -name '*.java')
D8_IN=$(find $OUT/classes -name '*.class')
[ -f "$ZXING" ] && D8_IN="$D8_IN $ZXING"
$BT/d8 --release --min-api 26 --lib $JAR --output $OUT/apk $D8_IN
# unpack resources from base.apk (manifest, res, assets) then add dex + lib
# aapt2 link already wrote manifest+res+assets into base.apk; zip dex and lib into it
(cd $OUT/apk && zip -q -r ../base.apk classes.dex lib)
$BT/zipalign -f -p 4 $OUT/base.apk $OUT/aligned.apk
KS=$HOME/.android/rindbench-debug.keystore
[ -f $KS ] || keytool -genkeypair -keystore $KS -storepass android -keypass android -alias rindbench -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=RindBench debug"
$BT/apksigner sign --ks $KS --ks-pass pass:android --key-pass pass:android --out $OUT/RindBench-android.apk $OUT/aligned.apk
$BT/apksigner verify $OUT/RindBench-android.apk && ls -la $OUT/RindBench-android.apk
